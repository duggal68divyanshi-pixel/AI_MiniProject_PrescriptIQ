import { useState, useEffect, useMemo } from "react";
import { getLiteratureMatrix } from "../../../services/api.js";

const ALL_COLUMNS = [
  ["research_problem", "Problem"],
  ["methodology", "Methodology"],
  ["model_or_algorithm", "Model / Algorithm"],
  ["dataset", "Dataset"],
  ["evaluation_metrics", "Evaluation Metrics"],
  ["key_results", "Key Results"],
  ["contributions", "Contributions"],
  ["limitations", "Limitations"],
];

const LOCAL_STORAGE_KEY = "nexus_matrix_visible_columns";

export default function MatrixTab({ projectId, indexedDocuments }) {
  const [matrix, setMatrix] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const [expanded, setExpanded] = useState(null); // documentId whose row is expanded
  const [searchQuery, setSearchQuery] = useState("");
  const [showColMenu, setShowColMenu] = useState(false);
  const [sortConfig, setSortConfig] = useState({ key: "title", direction: "asc" });

  const [visibleColumns, setVisibleColumns] = useState(() => {
    try {
      const saved = localStorage.getItem(LOCAL_STORAGE_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length > 0) return parsed;
      }
    } catch {
      // ignore
    }
    return ALL_COLUMNS.map((c) => c[0]);
  });

  const toggleColumn = (key) => {
    setVisibleColumns((prev) => {
      const next = prev.includes(key) ? prev.filter((k) => k !== key) : [...prev, key];
      if (next.length === 0) return prev; // keep at least 1 column
      try {
        localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(next));
      } catch {
        // ignore
      }
      return next;
    });
  };

  const activeColumns = useMemo(() => {
    return ALL_COLUMNS.filter(([key]) => visibleColumns.includes(key));
  }, [visibleColumns]);

  async function load(forceRefresh = false) {
    setLoading(true);
    setError(null);
    try {
      const result = await getLiteratureMatrix(projectId, forceRefresh);
      setMatrix(result);
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  }

  function handleSort(key) {
    setSortConfig((prev) => {
      if (prev.key === key) {
        return { key, direction: prev.direction === "asc" ? "desc" : "asc" };
      }
      return { key, direction: "asc" };
    });
  }

  const filteredAndSortedRows = useMemo(() => {
    if (!matrix?.rows) return [];
    let list = [...matrix.rows];

    // Real-time search filter
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      list = list.filter((r) => {
        const title = (r.title || r.filename || "").toLowerCase();
        const authors = (r.authors || []).join(" ").toLowerCase();
        const colMatch = ALL_COLUMNS.some(([k]) => (r[k] || "").toLowerCase().includes(q));
        return title.includes(q) || authors.includes(q) || colMatch;
      });
    }

    // Sort
    if (sortConfig.key) {
      list.sort((a, b) => {
        let valA = "";
        let valB = "";
        if (sortConfig.key === "title") {
          valA = a.title || a.filename || "";
          valB = b.title || b.filename || "";
        } else if (sortConfig.key === "year") {
          valA = a.publication_year ?? 0;
          valB = b.publication_year ?? 0;
          return sortConfig.direction === "asc" ? valA - valB : valB - valA;
        } else {
          valA = a[sortConfig.key] || "";
          valB = b[sortConfig.key] || "";
        }
        const cmp = String(valA).localeCompare(String(valB));
        return sortConfig.direction === "asc" ? cmp : -cmp;
      });
    }

    return list;
  }, [matrix, searchQuery, sortConfig]);

  function exportCSV() {
    if (!matrix || !matrix.rows.length) return;
    const headers = ["Paper Title", "Filename", "Authors", "Year", ...activeColumns.map((c) => c[1])];
    const rows = filteredAndSortedRows.map((r) => [
      `"${(r.title || "").replace(/"/g, '""')}"`,
      `"${(r.filename || "").replace(/"/g, '""')}"`,
      `"${(r.authors ? r.authors.join(", ") : "").replace(/"/g, '""')}"`,
      `"${r.publication_year || ""}"`,
      ...activeColumns.map(([key]) => `"${(r[key] || "").replace(/"/g, '""')}"`),
    ]);
    const csvContent =
      "data:text/csv;charset=utf-8," + [headers.join(","), ...rows.map((e) => e.join(","))].join("\n");
    const encodedUri = encodeURI(csvContent);
    const link = document.createElement("a");
    link.setAttribute("href", encodedUri);
    link.setAttribute("download", "literature_review_matrix.csv");
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  }

  function exportMarkdownReport() {
    if (!matrix || !matrix.rows.length) return;
    let md = "# Structured Literature Review Report\n\n";
    md += `*Generated by Research Nexus — ${filteredAndSortedRows.length} paper(s) included*\n\n`;
    md += "## Executive Summary of Literature\n\n";
    filteredAndSortedRows.forEach((r, idx) => {
      md += `### ${idx + 1}. ${r.title || r.filename}\n`;
      if (r.authors?.length) md += `- **Authors**: ${r.authors.join(", ")}\n`;
      if (r.publication_year) md += `- **Year**: ${r.publication_year}\n`;
      activeColumns.forEach(([key, label]) => {
        md += `- **${label}**: ${r[key] || "Not reported"}\n`;
      });
      md += "\n";
    });
    const blob = new Blob([md], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "literature_review_report.md";
    a.click();
    URL.revokeObjectURL(url);
  }

  function renderCellContent(text, isExpanded) {
    if (!text || text.toLowerCase().includes("not reported in the indexed text") || text.toLowerCase() === "not reported") {
      return (
        <span className="italic text-xs text-stone-400 select-none">
          Not reported in indexed text
        </span>
      );
    }
    return <p className={isExpanded ? "" : "line-clamp-3"}>{text}</p>;
  }

  function getSkippedDocName(docId) {
    const match = indexedDocuments?.find((d) => String(d.id) === String(docId));
    return match?.metadata?.title || match?.title || match?.filename || docId;
  }

  return (
    <div className="px-8 py-8">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <p className="font-display text-xl text-ink">Literature Review Matrix</p>
          <p className="mt-1 text-sm text-muted">
            Structured findings extracted from every indexed paper, generated on demand.
          </p>
        </div>
        <div className="flex flex-wrap gap-2 relative">
          {matrix && matrix.rows.length > 0 && (
            <>
              {/* Column Filter Dropdown */}
              <div className="relative">
                <button
                  onClick={() => setShowColMenu((v) => !v)}
                  className="rounded-md border border-line bg-white px-3 py-2 text-sm text-ink hover:border-pine-400 font-mono uppercase text-xs flex items-center gap-1.5"
                >
                  <span>Columns ({activeColumns.length}/{ALL_COLUMNS.length})</span>
                  <span>▾</span>
                </button>
                {showColMenu && (
                  <div className="absolute right-0 mt-1 z-30 w-52 rounded-md border border-line bg-white p-2 shadow-lg">
                    <p className="font-mono text-[10px] uppercase tracking-wider text-muted px-2 py-1">
                      Show/Hide Columns
                    </p>
                    {ALL_COLUMNS.map(([key, label]) => (
                      <label
                        key={key}
                        className="flex items-center gap-2 px-2 py-1 text-xs text-ink hover:bg-stone-50 rounded cursor-pointer"
                      >
                        <input
                          type="checkbox"
                          checked={visibleColumns.includes(key)}
                          onChange={() => toggleColumn(key)}
                          className="rounded border-line text-pine-600 focus:ring-pine-500"
                        />
                        <span>{label}</span>
                      </label>
                    ))}
                  </div>
                )}
              </div>

              <button
                onClick={exportCSV}
                className="rounded-md border border-line bg-white px-3 py-2 text-sm text-pine-700 hover:border-pine-400 font-mono uppercase text-xs"
              >
                Export CSV
              </button>
              <button
                onClick={exportMarkdownReport}
                className="rounded-md border border-line bg-white px-3 py-2 text-sm text-pine-700 hover:border-pine-400 font-mono uppercase text-xs"
              >
                Export Report (.md)
              </button>
            </>
          )}
          <button
            onClick={() => load(false)}
            disabled={loading || indexedDocuments.length === 0}
            className="rounded-md bg-pine-600 px-4 py-2 text-sm font-medium text-paper hover:bg-pine-700 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {loading ? "Generating…" : matrix ? "Refresh" : "Generate Matrix"}
          </button>
          {matrix && (
            <button
              onClick={() => load(true)}
              disabled={loading}
              className="rounded-md border border-line px-4 py-2 text-sm text-ink hover:border-pine-400"
            >
              Force re-analyze
            </button>
          )}
        </div>
      </div>

      {indexedDocuments.length === 0 && (
        <p className="mt-6 text-sm text-muted">No indexed papers in this project yet.</p>
      )}

      {error && (
        <div className="mt-4 rounded-md border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-800">
          {error}
        </div>
      )}

      {loading && !matrix && (
        <p className="mt-6 text-sm text-muted">
          Extracting structured findings for each paper — this runs a grounded retrieval + extraction pass per paper and can take a moment…
        </p>
      )}

      {matrix && matrix.rows.length > 0 && (
        <div className="mt-6">
          {/* Search bar & count */}
          <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search table by paper title, author, or keyword..."
              className="w-full max-w-sm rounded-md border border-line bg-white px-3 py-1.5 text-xs text-ink outline-none placeholder:text-muted focus:border-pine-400"
            />
            <span className="font-mono text-xs text-muted">
              Showing {filteredAndSortedRows.length} of {matrix.rows.length} paper(s)
            </span>
          </div>

          <div className="overflow-x-auto rounded-md border border-line">
            <table className="min-w-[1200px] border-collapse text-left text-sm">
              <thead>
                <tr className="border-b border-line bg-pine-50">
                  <th className="sticky left-0 z-10 bg-pine-50 px-4 py-2.5 font-mono text-[11px] uppercase tracking-wide text-pine-800 shadow-[3px_0_5px_-2px_rgba(0,0,0,0.1)] border-r border-line">
                    <div className="flex items-center gap-1.5">
                      <span>Paper</span>
                      <button
                        onClick={() => handleSort("title")}
                        className="text-[10px] hover:text-pine-900"
                        title="Sort by title"
                      >
                        {sortConfig.key === "title" ? (sortConfig.direction === "asc" ? "▲" : "▼") : "↕"}
                      </button>
                      <button
                        onClick={() => handleSort("year")}
                        className="text-[9px] text-muted hover:text-pine-900 ml-1 font-mono uppercase"
                        title="Sort by publication year"
                      >
                        [Yr {sortConfig.key === "year" ? (sortConfig.direction === "asc" ? "▲" : "▼") : "↕"}]
                      </button>
                    </div>
                  </th>
                  {activeColumns.map(([key, label]) => (
                    <th
                      key={key}
                      className="min-w-[200px] px-4 py-2.5 font-mono text-[11px] uppercase tracking-wide text-pine-800"
                    >
                      <div className="flex items-center gap-1">
                        <span>{label}</span>
                        <button
                          onClick={() => handleSort(key)}
                          className="text-[10px] text-muted hover:text-pine-900"
                          title={`Sort by ${label}`}
                        >
                          {sortConfig.key === key ? (sortConfig.direction === "asc" ? "▲" : "▼") : "↕"}
                        </button>
                      </div>
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {filteredAndSortedRows.map((row) => {
                  const isExpanded = expanded === row.document_id;
                  return (
                    <tr key={row.document_id} className="border-b border-line align-top hover:bg-stone-50/50">
                      <td className="sticky left-0 z-10 max-w-[230px] bg-white px-4 py-3 shadow-[3px_0_5px_-2px_rgba(0,0,0,0.06)] border-r border-line">
                        <p className="font-medium text-ink">{row.title || row.filename}</p>
                        {row.authors?.length > 0 && (
                          <p className="mt-0.5 text-xs text-muted">{row.authors.join(", ")}</p>
                        )}
                        {row.publication_year && (
                          <p className="text-xs text-muted">{row.publication_year}</p>
                        )}
                        <button
                          onClick={() => setExpanded(isExpanded ? null : row.document_id)}
                          className="mt-1 font-mono text-[11px] uppercase text-pine-700 hover:underline"
                        >
                          {isExpanded ? "Collapse" : "Expand"}
                        </button>
                      </td>
                      {activeColumns.map(([key]) => (
                        <td key={key} className="max-w-[280px] px-4 py-3 text-ink">
                          {renderCellContent(row[key], isExpanded)}
                        </td>
                      ))}
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {matrix && matrix.skipped.length > 0 && (
        <div className="mt-4 rounded-md border border-amber-200 bg-amber-50 px-4 py-3">
          <p className="font-mono text-[11px] uppercase tracking-wide text-amber-800 font-medium">
            {matrix.skipped.length} paper(s) could not be analyzed
          </p>
          {matrix.skipped.map((s) => (
            <p key={s.document_id} className="mt-1 text-xs text-amber-800">
              <strong>{getSkippedDocName(s.document_id)}</strong>: {s.reason}
            </p>
          ))}
        </div>
      )}
    </div>
  );
}

